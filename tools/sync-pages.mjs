const pagePath = (language, file) =>
    language.directory ? `/${language.directory}/${file}` : `/${file}`;

const indent = (value, spaces) => {
    const prefix = ' '.repeat(spaces);

    return value
        .trim()
        .split('\n')
        .map((line) => `${prefix}${line}`)
        .join('\n');
};

const renderNavLinks = (navLinks) =>
    indent(navLinks.map(({ href, label }) => `<a href="${href}">${label}</a>`).join('\n'), 12);

const renderAlternateLinks = (file) =>
    [
        ...languages.map(
            (language) =>
                `<link rel="alternate" hreflang="${language.code}" href="${SITE_URL}${pagePath(language, file)}" />`,
        ),
        `<link rel="alternate" hreflang="x-default" href="${SITE_URL}${pagePath(languages[0], file)}" />`,
    ].join('\n        ');

const renderLangSwitch = (currentLanguage, file) => {
    const links = languages.map((language) => {
        const current = language.code === currentLanguage.code ? ' aria-current="true"' : '';

        return `    <a href="${pagePath(language, file)}" hreflang="${language.code}" lang="${language.code}"${current}>${language.switchLabel}</a>`;
    });

    return [
        `<nav class="lang-switch" aria-label="${currentLanguage.switchAriaLabel}">`,
        ...links,
        '</nav>',
    ].join('\n            ');
};

const renderPage = (template, language, page, content) =>
    template
        .replaceAll('{{lang}}', language.code)
        .replaceAll('{{title}}', page.title)
        .replaceAll('{{description}}', page.description)
        .replaceAll('{{alternate_links}}', renderAlternateLinks(page.outputFile))
        .replaceAll('{{body_class}}', page.bodyClass)
        .replaceAll('{{subtitle}}', page.subtitle)
        .replaceAll('{{heading}}', page.heading)
        .replaceAll('{{nav_links}}', renderNavLinks(page.navLinks))
        .replaceAll('{{lang_switch}}', renderLangSwitch(language, page.outputFile))
        .replaceAll('{{footer_tagline}}', language.footerTagline)
        .replaceAll('{{legal_links_label}}', language.legalLinksLabel)
        .replaceAll('{{privacy_label}}', language.privacyLabel)
        .replaceAll('{{terms_label}}', language.termsLabel)
        .replaceAll('{{home_href}}', language.homeHref)
        .replaceAll('{{home_label}}', language.homeLabel)
        .replaceAll('{{content}}', indent(content, 12));

const syncLegalPages = async () => {
    const template = await readFile(resolve(templateDirectory, 'legal-shell.html'), 'utf8');

    for (const language of languages) {
        const outputDirectory = resolve(projectRoot, language.directory);

        await mkdir(outputDirectory, { recursive: true });

        for (const page of legalPages[language.code]) {
            const content = await readFile(resolve(templateDirectory, page.contentFile), 'utf8');
            const outputPath = resolve(outputDirectory, page.outputFile);
            const output = `${GENERATED_BANNER}\n${renderPage(template, language, page, content)}\n`;

            await writeFile(outputPath, output, 'utf8');
        }
    }
};

const main = async () => {
    await syncLegalPages();
};

main().catch((error) => {
    console.error(error);
    process.exitCode = 1;
});
